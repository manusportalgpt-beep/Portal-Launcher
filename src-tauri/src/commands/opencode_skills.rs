/// Раскладывает предустановленные навыки по папке лаунчера.
///
/// Существующие файлы не трогаем: пользователь может править навык, и его
/// изменения должны пережить обновление лаунчера.
pub fn ensure_builtin_skills() {
    let root = super::opencode::skills_dir();
    for (slug, body) in BUILTIN {
        let dir = root.join(slug);
        let file = dir.join("SKILL.md");
        if file.exists() {
            continue;
        }
        if std::fs::create_dir_all(&dir).is_err() {
            continue;
        }
        let _ = std::fs::write(&file, body);
    }
}
