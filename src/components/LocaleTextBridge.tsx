const EN: Record<string, string> = Object.fromEntries(
  Object.entries(RU).map(([english, russian]) => [russian, english]),
);

function translated(value: string, language: 'en' | 'ru') {
  const table = language === 'ru' ? RU : EN;
  const trimmed = value.trim();
  const replacement = table[trimmed];
  if (!replacement || replacement === trimmed) return value;
  const start = value.slice(0, value.indexOf(trimmed));
  const end = value.slice(value.indexOf(trimmed) + trimmed.length);
  return `${start}${replacement}${end}`;
}

export function LocaleTextBridge() {
  const language = useLanguageStore(state => state.lang);

  useEffect(() => {
    let busy = false;
    const apply = (root: ParentNode = document.body) => {
      if (busy) return;
      busy = true;
      try {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        const nodes: Text[] = [];
        while (walker.nextNode()) nodes.push(walker.currentNode as Text);
        for (const node of nodes) {
          const parent = node.parentElement;
          if (!parent || ['SCRIPT', 'STYLE', 'CODE'].includes(parent.tagName)) continue;
          const next = translated(node.textContent ?? '', language);
          if (next !== node.textContent) node.textContent = next;
        }
        const elements = root.querySelectorAll?.('[placeholder],[title],[aria-label]') ?? [];
        elements.forEach((element) => {
          for (const attribute of ['placeholder', 'title', 'aria-label']) {
            const current = element.getAttribute(attribute);
            if (!current) continue;
            const next = translated(current, language);
            if (next !== current) element.setAttribute(attribute, next);
          }
        });
      } finally {
        busy = false;
      }
    };

    apply();
    const observer = new MutationObserver(() => apply());
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);

  return null;
}

export default LocaleTextBridge;
